    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un vehículo para actualizar.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

      
        String placa = jTable1.getValueAt(fila, 0).toString();
        Vehiculo v = gestorVehiculos.buscarVehiculo(placa);
        if (v == null) {
            JOptionPane.showMessageDialog(this, "Vehículo no encontrado.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

    
        txtPlaca1.setText(v.getPlaca());
        txtMarca1.setText(v.getMarca());
        txtModelo1.setText(v.getModelo());
        txtAnio1.setText(String.valueOf(v.getAnio()));
        txtTipo1.setText(v.getTipo());
        txtEstado1.setText(v.getEstado());

        // Mostrar el diálogo
        jDialog2.setVisible(true);
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un vehículo para eliminar.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String placa = jTable1.getValueAt(fila, 0).toString();

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Seguro que desea eliminar el vehículo con placa " + placa + "?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

        if (opcion == JOptionPane.YES_OPTION) {
            try {
               // gestorVehiculos.eliminarVehiculo(placa);
                actualizarTabla();
                JOptionPane.showMessageDialog(this, "Vehículo eliminado con éxito.");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar el vehículo: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

