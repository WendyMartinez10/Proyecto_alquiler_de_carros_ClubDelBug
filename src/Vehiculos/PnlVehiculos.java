    private void buscarVehiculo() {
        String placa = txtBuscar.getText().trim();
        if (placa.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese la placa para buscar",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        Vehiculo vehiculo = gestorVehiculos.buscarVehiculo(placa); // Implementar este método en GestorVehiculos
        if (vehiculo == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Vehículo no encontrado",
                    "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        // Llenar los campos del formulario
        txtPlaca1.setText(vehiculo.getPlaca());
        txtMarca1.setText(vehiculo.getMarca());
        txtModelo1.setText(vehiculo.getModelo());
        txtAnio1.setText(String.valueOf(vehiculo.getAnio()));
        txtTipo1.setText(vehiculo.getTipo());
        txtEstado1.setText(vehiculo.getEstado());

        jDialog2.setVisible(true);
    }

