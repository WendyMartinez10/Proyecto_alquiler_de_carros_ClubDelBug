    private void crearVehiculo() {
        try {
            String placa = txtPlaca.getText().trim();
            String marca = txtMarca.getText().trim();
            String modelo = txtModelo.getText().trim();
            String anioStr = txtAnio.getText().trim();
            String tipo = txtTipo.getText().trim();
            String estado = txtEstado.getText().trim();

            if (placa.isEmpty() || marca.isEmpty() || modelo.isEmpty() || anioStr.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Placa, Marca, Modelo y Año son obligatorios",
                        "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            int anio;
            try {
                anio = Integer.parseInt(anioStr);
            } catch (NumberFormatException ex) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "El año debe ser un número válido",
                        "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            Vehiculo nuevoVehiculo = new Vehiculo(placa, marca, modelo, anio, tipo, estado);

            gestorVehiculos.agregarVehiculo(nuevoVehiculo);

            actualizarTabla();

            // Limpiar campos
            txtPlaca.setText("");
            txtMarca.setText("");
            txtModelo.setText("");
            txtAnio.setText("");
            txtTipo.setText("");
            txtEstado.setText("");

            jDialog1.setVisible(false);

            javax.swing.JOptionPane.showMessageDialog(this, "Vehículo creado con éxito");

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error al crear el vehículo: " + e.getMessage(),
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }


